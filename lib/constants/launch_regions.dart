String normalizeZip(String value) {
  final digits = value.replaceAll(RegExp(r'\D'), '');
  if (digits.length < 5) return digits;
  return digits.substring(0, 5);
}

bool isSupportedLaunchZip(String zip) {
  return kHoustonMetroZipCodes.contains(normalizeZip(zip));
}

String launchRegionForZip(String zip) {
  return isSupportedLaunchZip(zip)
      ? kLaunchRegionHoustonMetro
      : kLaunchRegionUnsupported;
}

String marketStatusForZip(String zip) {
  return isSupportedLaunchZip(zip)
      ? kMarketStatusActive
      : kMarketStatusWaitlist;
}

bool isWaitlistedProfile(Map<String, dynamic> profile) {
  final status = (profile['marketStatus'] as String?)?.trim().toLowerCase();
  return status == kMarketStatusWaitlist;
}
